import { chromium, expect } from '@playwright/test'
import { Decimal } from 'decimal.js'
import { mkdir } from 'node:fs/promises'

// Saved-data acceptance only: no login, extraction or refresh. Use an offline copied DB.
const origin = process.env.PRISM_V2_URL ?? 'http://127.0.0.1:4317'
const json = async path => { const response = await fetch(origin + path); expect(response.ok).toBe(true); return response.json() }
const before = await json('/api/exposure')
const progress = await json('/api/development')
expect(before.compositions).toHaveLength(5)
expect(progress.counts).toMatchObject({ portfolioFunds: 7, acquiredFunds: 6, qualifiedFunds: 5, usedFunds: 5 })
expect(progress.stages.find(stage => stage.id === 'identity')).toMatchObject({ state: 'open', summary: expect.stringContaining('Alphabet Class A and Class C') })
const nvidia = before.rows.find(row => row.isin === 'US67066G1040' && row.currency === 'EUR')
expect(nvidia.contributions.filter(item => item.kind === 'etf')).toHaveLength(5)
expect(nvidia.contributions.filter(item => item.kind === 'direct')).toHaveLength(1)
expect(nvidia.knownTotal).toBe('5432.1734288127589203')
expect(before.directStockCoverage).toHaveLength(21)
expect(before.directStockCoverage.filter(stock => stock.matchedFunds.length)).toHaveLength(13)
const world = await json('/api/development/etf/IE00B4L5Y983')
const nvda = world.rows.find(row => row.isin === nvidia.isin)
expect(world.illustrative.rows.find(row => row.row === nvda.row).state).toBe('included')
const hedged = await json('/api/development/etf/IE00BYVQ9F29')
expect(hedged.illustrative.rows.every(row => row.value === null)).toBe(true)
expect((await json('/api/development/etf/FR0010361683')).rows).toHaveLength(0)
await mkdir('v2/test-results/multi-etf/browser', { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = [], mutations = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.method() !== 'GET') mutations.push(request.url()) })
  await page.goto(`${origin}/#/development`)
  await expect(page.getByText(/1 missing composition; 1 need held-class semantics; 0 awaiting source checks/)).toBeVisible()
  await page.goto(`${origin}/#/fund/${world.isin}`)
  await expect(page.locator('#fund-detail-title')).toHaveText(world.name)
  await page.getByLabel('Filter retained rows').fill('NVIDIA')
  const row = page.locator('.progress-detail-table tbody tr').filter({ hasText: nvda.name })
  await expect(row).toContainText('Included')
  await expect(row).toContainText('707.37 EUR')
  await row.getByRole('link', { name: nvda.name, exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Security detail', exact: true })).toBeFocused()
  await expect(page.locator('.company-card > summary')).toContainText('5432.17 EUR')
  await expect(page.locator('.company-card tbody tr')).toHaveCount(6)
  await expect(page.locator('.selected-contribution')).toHaveCount(1)
  await expect(page.locator('.selected-contribution')).toContainText(world.isin)
  await expect(page.locator('.company-card')).toContainText('2064.04 EUR')
  await expect(page.locator('.company-card')).toContainText('3368.14 EUR')
  await page.screenshot({ path: 'v2/test-results/multi-etf/browser/nvidia.png', fullPage: true })
  await page.goBack()
  await expect(page.getByLabel('Filter retained rows')).toHaveValue('NVIDIA')
  await page.goto(`${origin}/#/security/US02079K3059`)
  await expect(page.locator('.issuer-group')).toContainText('2321.18 EUR known combined value')
  await expect(page.locator('.issuer-group')).toContainText('already included in portfolio coverage')
  await page.locator('.issuer-group').getByRole('link').filter({ hasText: 'US02079K1079' }).first().click()
  await expect(page.locator('.company-card')).toContainText('US02079K1079')
  await expect(page.locator('.issuer-group')).toContainText('2321.18 EUR')
  for (const width of [320, 390]) {
    await page.setViewportSize({ width, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.locator('.issuer-group summary').focus()
    await page.keyboard.press('Enter')
    await expect(page.locator('.issuer-group details')).toHaveAttribute('open', '')
    await page.screenshot({ path: `v2/test-results/multi-etf/browser/alphabet-${width}.png`, fullPage: true })
    await page.keyboard.press('Enter')
  }
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto(`${origin}/#/breakdown`)
  await page.getByText(/^Direct stock identifier coverage/).click()
  const coverage = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^Direct stock identifier coverage/ }) }).last()
  await expect(coverage.locator('tbody tr')).toHaveCount(21)
  await expect(coverage.locator('tr').filter({ hasText: 'CA87320M2004' })).toContainText('Unknown')
  await expect(coverage.locator('tr').filter({ hasText: 'AU0000066086' })).toContainText('No exact match')
  await page.getByLabel('Find a security or ISIN').fill('NVIDIA')
  await page.getByText(/^Portfolio-wide coverage gaps/).click()
  await expect(page.getByText(/not exposure to the selected security/)).toBeVisible()
  expect(errors).toEqual([])
  expect(mutations).toEqual([])
  const after = await json('/api/exposure')
  expect(after.rows).toEqual(before.rows)
  expect(after.coverage).toEqual(before.coverage)
  expect(after.issuerGroups).toEqual(before.issuerGroups)
  expect(new Decimal(after.coverage[0].knownCompanyValue).toFixed(2)).toBe('41190.97')
  console.log('Passed: five-source World/NVIDIA journey, contribution highlight, 21-stock coverage, bounded Alphabet grouping, unknown gaps, 320/390px layout, keyboard, no mutations and unchanged exposure.')
} finally { await browser.close() }
